import {createRelay} from '../server.mjs';
import {mkdtempSync,writeFileSync,existsSync,rmSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../data');
const dataDir=mkdtempSync(path.join(root,'map-native-preview-'));
const stateFile=path.join(root,'map-native-preview.json');
const stopFile=path.join(root,'map-native-preview.stop');
if(existsSync(stopFile))rmSync(stopFile);
let searches=0;
const server=createRelay({dataDir,publicUrl:'',kakaoKey:'fixture',mapKey:'',mobilityKey:'',fetchPlaces:async()=>++searches===1?new Response('{}',{status:503}):Response.json({documents:[{id:'preview-result',place_name:'화면 검증 검색 카페',road_address_name:'검증용 주소',x:'127.01',y:'37.51',category_group_code:'CE7'}]})});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${server.address().port}`;
const post=async(route,data,token)=>{const r=await fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:`Bearer ${token}`}:{})},body:JSON.stringify(data)});if(!r.ok)throw Error('Preview setup failed');return r.json();};
const room=await post('/api/rooms',{name:'[개발검증] 완료 코스 삭제'});
const ids=[];
for(const [i,name] of ['검증 식당','검증 카페'].entries())ids.push((await post(`/api/rooms/${room.id}/places`,{name,latitude:37.5+i*.01,longitude:127,sender:'동행',note:'original'},room.ownerToken)).id);
const plan=await post(`/api/rooms/${room.id}/plan`,{origin:{latitude:37.49,longitude:127},maxStops:2,assumedMinutes:20},room.ownerToken);
const saved=await post(`/api/rooms/${room.id}/course`,{action:'choose',planId:plan.plans[0].id},room.ownerToken);
for(const stop of saved.course.stops)await post(`/api/rooms/${room.id}/course`,{action:'visit',placeId:stop.placeId},room.ownerToken);
writeFileSync(stateFile,JSON.stringify({base,id:room.id,ownerToken:room.ownerToken,joinToken:room.joinToken,placeId:ids[0]}));
console.log('Completed-course QA fixture ready on loopback.');
let closed=false;
const stop=()=>{if(closed)return;closed=true;clearInterval(poll);clearTimeout(timeout);server.closeAllConnections();server.close(()=>{if(!path.resolve(dataDir).startsWith(root+path.sep))throw Error('Unexpected preview directory');rmSync(dataDir,{recursive:true,force:true});for(const f of [stateFile,stopFile])if(existsSync(f))rmSync(f);console.log('Preview closed and fixtures removed.');});};
const poll=setInterval(()=>{if(existsSync(stopFile))stop();},500);
const timeout=setTimeout(stop,15*60*1000);
